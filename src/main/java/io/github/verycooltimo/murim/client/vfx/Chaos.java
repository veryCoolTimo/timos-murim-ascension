package io.github.verycooltimo.murim.client.vfx;

/**
 * Источник детерминированного беспорядка для эффектов.
 *
 * <p><b>Зачем.</b> Симметрия наших эффектов была заложена в самой первой строке кода:
 * углы задавались как {@code i * 2π / N}, что по построению даёт правильный многоугольник,
 * а радиус как {@code sin(π·t)} — симметричное веретено. Никакая яркость и никакое
 * количество прядей этого не лечат. Живая форма требует, чтобы каждая прядь имела
 * СВОЮ фазу, СВОЁ направление закрутки и СВОЙ профиль.
 *
 * <p><b>Почему не Random.</b> Случайные числа на каждый кадр дают дрожание, зависящее
 * от частоты кадров: на быстрой машине эффект выглядит иначе, чем на медленной.
 * Здесь беспорядок выводится из ХЕША индекса и семени — одна и та же прядь всегда
 * получает одни и те же значения, но соседние пряди не похожи друг на друга.
 *
 * <p>Хеш — splitmix64: он дёшев, не требует состояния и хорошо перемешивает младшие биты,
 * в отличие от простого умножения, где соседние индексы дают близкие результаты.
 */
public final class Chaos {

    /**
     * Перемешивание splitmix64.
     *
     * <p>Константы взяты из оригинального алгоритма и подобраны так, чтобы изменение
     * одного бита входа меняло примерно половину битов выхода.
     */
    public static long hash(long value) {
        long z = value + 0x9E3779B97F4A7C15L;
        z = (z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9L;
        z = (z ^ (z >>> 27)) * 0x94D049BB133111EBL;
        return z ^ (z >>> 31);
    }

    /** Значение от нуля до единицы по двум ключам: индексу пряди и семени эффекта. */
    public static float unit(int index, long seed) {
        // Берём старшие биты: у splitmix64 они перемешаны лучше всего.
        return (hash(index * 0x2545F4914F6CDD1DL + seed) >>> 11) * 0x1.0p-53F;
    }

    /** Значение в заданном диапазоне. */
    public static float range(int index, long seed, float min, float max) {
        return min + unit(index, seed) * (max - min);
    }

    /**
     * Направление закрутки пряди: плюс или минус единица.
     *
     * <p>Однонаправленные витки читаются как вихрь — тот самый «ураган в руке».
     * Встречные читаются как беспорядок. Доля обратных берётся заметной, но меньшей
     * половины: при равенстве форма распадается на кашу.
     */
    public static float spin(int index, long seed, float reverseShare) {
        return unit(index, seed ^ 0x5DEECE66DL) < reverseShare ? -1.0F : 1.0F;
    }

    /**
     * Профиль ширины вдоль пряди — АСИММЕТРИЧНЫЙ.
     *
     * <p>Синус даёт пик ровно посередине и одинаковые концы: получается веретено,
     * которое глаз читает как геометрическую фигуру. У живого следа утолщение смещено
     * к одному концу, а второй конец длиннее и тоньше.
     *
     * @param t    положение вдоль пряди от нуля до единицы
     * @param peak где находится утолщение; 0.8 означает «ближе к концу»
     */
    public static float widthProfile(float t, float peak) {
        if (t <= 0.0F || t >= 1.0F) {
            return 0.0F;
        }
        // Две разные степени по сторонам от пика: короткий крутой подъём и длинный спад.
        return t < peak
                ? (float) Math.pow(t / peak, 0.55D)
                : (float) Math.pow((1.0F - t) / (1.0F - peak), 1.7D);
    }

    /**
     * Плотность прядей у конца.
     *
     * <p>На референсе линий тем больше, чем ближе к ладони. Равномерное распределение
     * по углу этого не даёт: нужно смещать пряди к средоточию неравномерно.
     *
     * @return множитель радиуса; ближе к единице — дальше от средоточия
     */
    public static float densityBias(int index, int count, long seed) {
        float even = count <= 1 ? 0.0F : index / (float) (count - 1);
        // Квадрат сгущает пряди у нуля; примесь хеша убирает регулярность сгущения.
        float biased = even * even;
        return biased * 0.75F + unit(index, seed ^ 0xA24BAED4963EE407L) * 0.25F;
    }

    private Chaos() {
    }
}
