package io.github.verycooltimo.murim.decor;

import io.github.verycooltimo.murim.MurimMod;
import java.util.List;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredItem;
import net.neoforged.neoforge.registries.DeferredRegister;

/** Alchemy, kitchen and desk decor; assets are generated by tools/art/int_workshop.py. */
public final class IntWorkshop {
    private static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks(MurimMod.MODID);
    private static final DeferredRegister<net.minecraft.world.effect.MobEffect> EFFECTS =
            DeferredRegister.create(net.minecraft.core.registries.Registries.MOB_EFFECT, MurimMod.MODID);
    public static final net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.effect.MobEffect, TipsyEffect> TIPSY =
            EFFECTS.register("tipsy", TipsyEffect::new);
    public static final net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.effect.MobEffect, HangoverEffect> HANGOVER =
            EFFECTS.register("hangover", HangoverEffect::new);
    private static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(MurimMod.MODID);

    public static final DeferredBlock<IntPillCabinetBlock> PILL_CABINET = BLOCKS.registerBlock("int_pill_cabinet",
            IntPillCabinetBlock::new, wood().pushReaction(PushReaction.DESTROY));
    public static final DeferredBlock<IntHeaterBlock> ALCHEMY_FURNACE = BLOCKS.registerBlock("int_alchemy_furnace",
            p -> new IntHeaterBlock(p, false), heater(SoundType.METAL));
    public static final DeferredBlock<IntHeaterBlock> KITCHEN_STOVE = BLOCKS.registerBlock("int_kitchen_stove",
            p -> new IntHeaterBlock(p, true), heater(SoundType.STONE));
    public static final DeferredBlock<IntTabletopBlock.ThreeVariants> TABLEWARE = BLOCKS.registerBlock("int_tableware",
            p -> new IntTabletopBlock.ThreeVariants(p, IntTabletopBlock.Kind.TABLEWARE), ceramic());
    public static final DeferredBlock<IntTabletopBlock.TeaTray> TEA_TRAY = BLOCKS.registerBlock("int_tea_tray",
            IntTabletopBlock.TeaTray::new, wood().strength(0.5F).pushReaction(PushReaction.DESTROY));
    public static final DeferredBlock<IntTabletopBlock> ABACUS_LEDGER = BLOCKS.registerBlock("int_abacus_ledger",
            p -> new IntTabletopBlock(p, IntTabletopBlock.Kind.ABACUS), wood().strength(0.5F).pushReaction(PushReaction.DESTROY));
    public static final DeferredBlock<IntTabletopBlock> SCALES_MORTAR = BLOCKS.registerBlock("int_scales_mortar",
            p -> new IntTabletopBlock(p, IntTabletopBlock.Kind.SCALES), ceramic());
    /** Black lacquer pill box with a gold medallion on the lid (author 24.10, refs pills005/010/027); assets: tools/art/pill_art/box_build.py. */
    public static final DeferredBlock<PillBoxBlock> PILL_BOX = BLOCKS.registerBlock("int_pill_box", PillBoxBlock::new, lacquer());
    public static final DeferredBlock<PillCrateBlock> PILL_CRATE = BLOCKS.registerBlock("pill_crate", PillCrateBlock::new, wood());
    public static final DeferredBlock<WineBlock> WINE_JAR = BLOCKS.registerBlock("wine_jar", p -> new WineBlock(p, false), ceramic());
    public static final DeferredBlock<WineBlock> WINE_CUP = BLOCKS.registerBlock("wine_cup", p -> new WineBlock(p, true), ceramic());
    public static final DeferredBlock<DiningTableBlock> LOW_TEA_TABLE = BLOCKS.registerBlock("low_tea_table", DiningTableBlock::new, wood());
    public static final DeferredItem<net.minecraft.world.item.Item> CAVE_NOTE = ITEMS.register("chungmyung_note", p -> new CaveNoteItem(new net.minecraft.world.item.Item.Properties().stacksTo(1)));
    public static final DeferredItem<net.minecraft.world.item.Item> EMPTY_WINE_JAR = ITEMS.register("empty_wine_jar", () -> new net.minecraft.world.item.Item(new net.minecraft.world.item.Item.Properties()));
    public static final DeferredItem<net.minecraft.world.item.Item> CRACKED_BOWL = ITEMS.register("cracked_bowl", () -> new net.minecraft.world.item.Item(new net.minecraft.world.item.Item.Properties()));
    public static final DeferredItem<net.minecraft.world.item.Item> WORN_PRACTICE_SWORD = ITEMS.register("worn_practice_sword", () -> new net.minecraft.world.item.Item(new net.minecraft.world.item.Item.Properties()));
    private static final DeferredRegister<net.minecraft.world.level.block.entity.BlockEntityType<?>> BLOCK_ENTITIES =
            DeferredRegister.create(net.minecraft.core.registries.Registries.BLOCK_ENTITY_TYPE, MurimMod.MODID);
    public static final net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.level.block.entity.BlockEntityType<?>,
            net.minecraft.world.level.block.entity.BlockEntityType<PillBoxBlockEntity>> PILL_BOX_ENTITY = BLOCK_ENTITIES.register(
            "int_pill_box", () -> net.minecraft.world.level.block.entity.BlockEntityType.Builder.of(PillBoxBlockEntity::new, PILL_BOX.get()).build(null));
    public static final net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.level.block.entity.BlockEntityType<?>,
            net.minecraft.world.level.block.entity.BlockEntityType<PillBoxBlockEntity>> PILL_CRATE_ENTITY = BLOCK_ENTITIES.register(
            "pill_crate", () -> net.minecraft.world.level.block.entity.BlockEntityType.Builder.of(PillBoxBlockEntity::new, PILL_CRATE.get()).build(null));
    private static final DeferredRegister<net.minecraft.world.inventory.MenuType<?>> MENUS =
            DeferredRegister.create(net.minecraft.core.registries.Registries.MENU, MurimMod.MODID);
    public static final net.neoforged.neoforge.registries.DeferredHolder<net.minecraft.world.inventory.MenuType<?>,
            net.minecraft.world.inventory.MenuType<PillBoxMenu>> PILL_BOX_MENU = MENUS.register("pill_box",
            () -> net.neoforged.neoforge.common.extensions.IMenuTypeExtension.create(PillBoxMenu::fromNetwork));
    public static final DeferredBlock<IntTabletopBlock.ThreeVariants> HERB_JARS = BLOCKS.registerBlock("int_herb_jars",
            p -> new IntTabletopBlock.ThreeVariants(p, IntTabletopBlock.Kind.JARS), ceramic());

    public static final List<DeferredBlock<? extends Block>> ALL = List.of(PILL_CABINET, ALCHEMY_FURNACE,
            KITCHEN_STOVE, TABLEWARE, TEA_TRAY, ABACUS_LEDGER, SCALES_MORTAR, PILL_BOX, HERB_JARS, PILL_CRATE, WINE_JAR, WINE_CUP, LOW_TEA_TABLE);
    private static final List<DeferredItem<BlockItem>> ITEMS_ALL = ALL.stream().map(b -> b == PILL_BOX
            ? ITEMS.<BlockItem>register("int_pill_box", id -> new PillBoxItem(PILL_BOX.get(), new net.minecraft.world.item.Item.Properties()))
            : b == PILL_CRATE
                    ? ITEMS.<BlockItem>register("pill_crate", id -> new BlockItem(PILL_CRATE.get(), new net.minecraft.world.item.Item.Properties().stacksTo(1)))
                    : ITEMS.registerSimpleBlockItem(b)).toList();

    private IntWorkshop() {
    }

    public static BlockItem item(DeferredBlock<? extends Block> block) {
        return ITEMS_ALL.get(ALL.indexOf(block)).get();
    }

    private static BlockBehaviour.Properties wood() {
        return BlockBehaviour.Properties.of().mapColor(MapColor.TERRACOTTA_BROWN).strength(2.0F, 3.0F)
                .sound(SoundType.WOOD).noOcclusion().ignitedByLava();
    }

    private static BlockBehaviour.Properties lacquer() {
        return BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BLACK).strength(0.5F)
                .sound(SoundType.WOOD).noOcclusion().ignitedByLava().pushReaction(PushReaction.DESTROY);
    }

    private static BlockBehaviour.Properties ceramic() {
        return BlockBehaviour.Properties.of().mapColor(MapColor.TERRACOTTA_CYAN).strength(0.5F)
                .sound(SoundType.DECORATED_POT).noOcclusion().pushReaction(PushReaction.DESTROY);
    }

    private static BlockBehaviour.Properties heater(SoundType sound) {
        return BlockBehaviour.Properties.of().mapColor(MapColor.STONE).strength(3.5F).sound(sound).noOcclusion()
                .lightLevel(s -> s.getValue(BlockStateProperties.LIT) ? 10 : 0);
    }

    private static void tabs(BuildCreativeModeTabContentsEvent event) {
        if (event.getTabKey().equals(io.github.verycooltimo.murim.registry.ModCreativeTabs.MURIM.getKey())) {
            event.accept(CAVE_NOTE.get());
            event.accept(EMPTY_WINE_JAR.get());
            event.accept(CRACKED_BOWL.get());
            event.accept(WORN_PRACTICE_SWORD.get());
            ITEMS_ALL.forEach(i -> event.accept(new ItemStack(i.get())));
        }
    }

    public static void register(IEventBus modBus) {
        EFFECTS.register(modBus);
        BLOCKS.register(modBus);
        BLOCK_ENTITIES.register(modBus);
        MENUS.register(modBus);
        ITEMS.register(modBus);
        modBus.addListener(IntWorkshop::tabs);
    }
}
