package io.github.verycooltimo.murim.decor;

import io.github.verycooltimo.murim.MurimMod;
import java.util.List;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.DoubleHighBlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.NoteBlockInstrument;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredItem;
import net.neoforged.neoforge.registries.DeferredRegister;

/** Hall entrance and substantial posts of build2/ref_06; resources generated by tools/art/hall_joinery.py. */
public final class HallJoinery {

    private static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks(MurimMod.MODID);
    private static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(MurimMod.MODID);

    public static final DeferredBlock<HallDoorBlock> HALL_DOOR = BLOCKS.registerBlock("hall_door",
            HallDoorBlock::new, timber(MapColor.COLOR_RED).strength(3.0F).pushReaction(PushReaction.DESTROY));
    public static final DeferredBlock<ThickPillarBlock> THICK_RED_PILLAR = BLOCKS.registerBlock("thick_red_pillar",
            ThickPillarBlock::new, timber(MapColor.COLOR_RED));
    public static final DeferredBlock<ThickPillarBlock> THICK_WHITE_PILLAR = BLOCKS.registerBlock("thick_white_pillar",
            ThickPillarBlock::new, timber(MapColor.SNOW));

    public static final DeferredItem<DoubleHighBlockItem> HALL_DOOR_ITEM = ITEMS.register("hall_door",
            () -> new DoubleHighBlockItem(HALL_DOOR.get(), new Item.Properties()));
    public static final DeferredItem<BlockItem> THICK_RED_PILLAR_ITEM = ITEMS.registerSimpleBlockItem(THICK_RED_PILLAR);
    public static final DeferredItem<BlockItem> THICK_WHITE_PILLAR_ITEM = ITEMS.registerSimpleBlockItem(THICK_WHITE_PILLAR);

    private static final List<DeferredBlock<? extends Block>> ALL = List.of(HALL_DOOR, THICK_RED_PILLAR, THICK_WHITE_PILLAR);
    private static final List<DeferredItem<? extends BlockItem>> ITEMS_ALL = List.of(
            HALL_DOOR_ITEM, THICK_RED_PILLAR_ITEM, THICK_WHITE_PILLAR_ITEM);

    private HallJoinery() {
    }

    private static BlockBehaviour.Properties timber(MapColor colour) {
        return BlockBehaviour.Properties.of().mapColor(colour).instrument(NoteBlockInstrument.BASS)
                .strength(2.0F, 3.0F).sound(SoundType.WOOD).noOcclusion().ignitedByLava()
                .isViewBlocking((s, l, p) -> false).isSuffocating((s, l, p) -> false);
    }

    public static BlockItem item(DeferredBlock<? extends Block> block) {
        return ITEMS_ALL.get(ALL.indexOf(block)).get();
    }

    private static void tabs(BuildCreativeModeTabContentsEvent event) {
        if (event.getTabKey().equals(io.github.verycooltimo.murim.registry.ModCreativeTabs.MURIM.getKey())) {
            for (DeferredItem<? extends BlockItem> item : ITEMS_ALL) {
                event.accept(new ItemStack(item.get()));
            }
        }
    }

    public static void register(IEventBus modBus) {
        BLOCKS.register(modBus);
        ITEMS.register(modBus);
        modBus.addListener(HallJoinery::tabs);
    }
}
