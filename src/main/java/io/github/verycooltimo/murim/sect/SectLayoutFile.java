    public record Waypoint(String id, BlockPos pos, String kind, String ref, String room) {
    }

    public record Edge(int index, String a, String b, int length, List<BlockPos> via, List<String> crosses, boolean stairs,
                       boolean oneWay) {
        /** The same two waypoints (in either order), whatever the way between them. */
        public boolean samePair(Edge o) {
            return a.equals(o.a) && b.equals(o.b) || a.equals(o.b) && b.equals(o.a);
        }

        /** The same way: the same pair and the same cells between them, walked in either direction. */
        public boolean sameWay(Edge o) {
            if (!samePair(o) || oneWay != o.oneWay) {
                return false;
            }
            boolean forward = a.equals(o.a);
            List<BlockPos> v = new ArrayList<>(o.via);
            List<String> c = new ArrayList<>(o.crosses);
            if (!forward) {
                java.util.Collections.reverse(v);
                java.util.Collections.reverse(c);
            }
            return via.equals(v) && crosses.equals(c);
        }
    }

    public record Zone(String id, Rect rect, int y) {
    }

