    /** Rooms whose floor covers the cell (several when the bounds of L-shaped rooms overlap). */
    public List<Room> roomsAt(BlockPos feet) {
        List<Room> out = new ArrayList<>(2);
        for (Room r : rooms.values()) {
            if (Math.abs(r.y() - feet.getY()) <= 1 && r.bounds().contains(feet.getX(), feet.getZ())) {
                out.add(r);
            }
        }
        return out;
    }

    /** Best single room of the cell: the one whose portal is nearest to it. */
    public Room roomAt(BlockPos feet) {
        Room best = null;
        double bestD = Double.MAX_VALUE;
        for (Room r : roomsAt(feet)) {
            double d = Double.MAX_VALUE;
            for (String w : r.portals()) {
                Waypoint wp = waypoints.get(w);
                if (wp != null) {
                    d = Math.min(d, wp.pos().distSqr(feet));
                }
            }
            if (best == null || d < bestD) {
                best = r;
                bestD = d;
            }
        }
        return best;
    }

    // ------------------------------------------------------------------ route search

    /**
     * Cheapest route (Dijkstra over the edges; {@code one_way} edges only a to b) from any start link to any goal
     * link. Edges in {@code banned} are skipped (stuck recovery). Null: no route.
     */
    public Route route(List<Link> starts, List<Link> goals, Set<Integer> banned) {
        Map<String, Double> dist = new HashMap<>();
        Map<String, Edge> via = new HashMap<>();
        Map<String, String> from = new HashMap<>();
        record Entry(String node, double cost) {
        }
        PriorityQueue<Entry> open = new PriorityQueue<>(Comparator.comparingDouble(Entry::cost));
        for (Link s : starts) {
            if (waypoints.containsKey(s.waypoint()) && s.cost() < dist.getOrDefault(s.waypoint(), Double.MAX_VALUE)) {
                dist.put(s.waypoint(), s.cost());
                open.add(new Entry(s.waypoint(), s.cost()));
            }
        }
        Map<String, Double> goalCost = new HashMap<>();
        for (Link g : goals) {
            goalCost.merge(g.waypoint(), g.cost(), Math::min);
        }
        Set<String> done = new HashSet<>();
        String bestGoal = null;
        double bestTotal = Double.MAX_VALUE;
        while (!open.isEmpty()) {
            Entry cur = open.poll();
            if (!done.add(cur.node())) {
                continue;
            }
            if (cur.cost() >= bestTotal) {
                break;
            }
            Double extra = goalCost.get(cur.node());
            if (extra != null && cur.cost() + extra < bestTotal) {
                bestTotal = cur.cost() + extra;
                bestGoal = cur.node();
            }
            for (Edge e : adjacency.getOrDefault(cur.node(), List.of())) {
                if (banned != null && banned.contains(e.index())) {
                    continue;
                }
                String next = e.a().equals(cur.node()) ? e.b() : e.a();
                if (!waypoints.containsKey(next)) {
                    continue;
                }
                double c = cur.cost() + e.length() + (e.stairs() ? 1.0D : 0.0D);
                if (c < dist.getOrDefault(next, Double.MAX_VALUE)) {
                    dist.put(next, c);
                    via.put(next, e);
                    from.put(next, cur.node());
                    open.add(new Entry(next, c));
                }
            }
        }
        if (bestGoal == null) {
            return null;
        }
        List<String> nodes = new ArrayList<>();
        List<Edge> used = new ArrayList<>();
        String n = bestGoal;
        nodes.add(n);
        while (via.containsKey(n)) {
            used.add(via.get(n));
            n = from.get(n);
            nodes.add(n);
        }
        Collections.reverse(nodes);
        Collections.reverse(used);
        return new Route(nodes, used, bestTotal);
    }

    /** Route between two waypoints. */
    public Route route(String from, String to) {
        return route(List.of(new Link(from, 0)), List.of(new Link(to, 0)), null);
    }

    /** Waypoints within {@code radius} blocks (and {@code dy} levels) of a cell, nearest first, as route links. */
    public List<Link> linksNear(BlockPos feet, double radius, int dy, int limit) {
        List<Link> out = new ArrayList<>();
        for (Waypoint w : waypoints.values()) {
            if (Math.abs(w.pos().getY() - feet.getY()) > dy) {
                continue;
            }
            double d = Math.sqrt(w.pos().distSqr(feet));
            if (d <= radius) {
                out.add(new Link(w.id(), d));
            }
        }
        out.sort(Comparator.comparingDouble(Link::cost));
        return out.size() > limit ? new ArrayList<>(out.subList(0, limit)) : out;
    }

    /** Route links for a cell: the portals of the rooms around it, else the nearest waypoints. */
    public List<Link> linksFor(BlockPos feet, String roomHint) {
        return linksFor(feet, roomHint, null);
    }

    /**
     * As {@link #linksFor(BlockPos, String)}; outdoors only waypoints in a clear line (no wall between) count, so a
     * waypoint on the other side of a wall is never the start of a route. Without any clear one, the nearest ones.
     */
    public List<Link> linksFor(BlockPos feet, String roomHint, java.util.function.BiPredicate<BlockPos, BlockPos> clear) {
        List<Link> out = new ArrayList<>();
        List<Room> around = new ArrayList<>();
        if (roomHint != null && rooms.containsKey(roomHint)) {
            around.add(rooms.get(roomHint));
        } else {
            around.addAll(roomsAt(feet));
        }
        for (Room r : around) {
            for (String id : r.portals()) {
                Waypoint w = waypoints.get(id);
                if (w != null) {
                    out.add(new Link(id, Math.sqrt(w.pos().distSqr(feet))));
                }
            }
        }
        if (out.isEmpty()) {
            List<Link> near = linksNear(feet, 16.0D, 3, clear == null ? 6 : 16);
            if (clear != null) {
                List<Link> seen = new ArrayList<>();
                for (Link l : near) {
                    if (clear.test(feet, waypoints.get(l.waypoint()).pos())) {
                        seen.add(l);
                    }
                }
                if (!seen.isEmpty()) {
                    near = seen.size() > 6 ? new ArrayList<>(seen.subList(0, 6)) : seen;
                }
            }
            out.addAll(near.size() > 6 ? near.subList(0, 6) : near);
        }
        return out;
    }

    // ------------------------------------------------------------------ places for dialogue

    /** Function word of the place under a cell: the room's function, else the building's, else the zone, else "". */
    public String placeFunction(BlockPos feet) {
        Room r = roomAt(feet);
        if (r != null) {
            Building b = buildings.get(r.building());
            String f = r.function();
            if (b != null && ("hall".equals(f) || "room".equals(f) || "corridor".equals(f) || "stair_hall".equals(f)
                    || "single_room".equals(f) && !b.id().startsWith("elder"))) {
                return b.function() == null ? f : b.function();
            }
            return f;
        }
        for (Building b : buildings.values()) {
            for (Rect box : b.boxes()) {
                if (box.contains(feet.getX(), feet.getZ())) {
                    return b.function() == null ? b.id() : b.function();
                }
            }
        }
        for (Zone z : zones.values()) {
            if (z.rect().contains(feet.getX(), feet.getZ()) && Math.abs(z.y() - feet.getY()) <= 2) {
                return z.id();
            }
        }
        return "";
    }

    // ------------------------------------------------------------------ loading

    private static volatile SectLayoutFile cached;
    private static volatile String cachedKey = "";

    /** The shipped file anchored to the live site, cached per site frame. Null: the resource is missing or broken. */
    public static SectLayoutFile anchored(MountHuaSite site) {
        String key = site.centerX() + "/" + site.centerZ() + "/" + site.baseY() + "/" + site.rotation();
        SectLayoutFile hit = cached;
        if (hit != null && key.equals(cachedKey)) {
            return hit;
        }
        synchronized (SectLayoutFile.class) {
            if (cached != null && key.equals(cachedKey)) {
                return cached;
            }
            SectLayoutFile loaded = loadResource(frame -> Anchor.to(frame, site));
            if (loaded != null) {
                cached = loaded;
                cachedKey = key;
            }
            return loaded;
        }
    }

    /** The shipped file in the world it was extracted from (no transform). */
    public static SectLayoutFile shipped() {
        return loadResource(Anchor::identity);
    }

    private static SectLayoutFile loadResource(java.util.function.Function<Frame, Anchor> anchor) {
        try (InputStream in = SectLayoutFile.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                return null;
            }
            return parse(new InputStreamReader(in, StandardCharsets.UTF_8), anchor);
        } catch (IOException | RuntimeException e) {
            io.github.verycooltimo.murim.MurimMod.LOGGER.warn("Sect layout file unreadable: {}", e.toString());
            return null;
        }
    }

    /** Parse a file of the schema; {@code anchor} turns the stored frame into the transform to apply. */
    public static SectLayoutFile parse(Reader reader, java.util.function.Function<Frame, Anchor> anchor) {
        JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
        JsonObject f = root.getAsJsonObject("frame");
        Frame frame = new Frame(f.get("center_x").getAsInt(), f.get("center_z").getAsInt(), f.get("base_y").getAsInt(),
                f.has("rotation") ? f.get("rotation").getAsInt() : 0);
        Anchor a = anchor.apply(frame);
        Map<String, String> roles = new LinkedHashMap<>();
        JsonObject rp = has(root, "roster_plan") ? root.getAsJsonObject("roster_plan") : new JsonObject();
        if (has(rp, "roster_to_layout_role")) {
            rp.getAsJsonObject("roster_to_layout_role").entrySet().forEach(e -> roles.put(e.getKey(), e.getValue().getAsString()));
        }
        List<Building> buildings = new ArrayList<>();
        for (JsonElement e : arr(root, "buildings")) {
            JsonObject o = e.getAsJsonObject();
            List<Rect> boxes = new ArrayList<>();
            if (has(o, "wall_boxes")) {
                for (JsonElement w : o.getAsJsonArray("wall_boxes")) {
                    JsonArray b = w.getAsJsonObject().getAsJsonArray("box");
                    // schema: [x0, x1, z0, z1]
                    boxes.add(a.rect(new Rect(b.get(0).getAsInt(), b.get(2).getAsInt(), b.get(1).getAsInt(), b.get(3).getAsInt())));
                }
            }
            buildings.add(new Building(str(o, "id"), str(o, "function"), strings(o, "rooms"), strings(o, "doors"), boxes));
        }
        List<Room> rooms = new ArrayList<>();
        for (JsonElement e : arr(root, "rooms")) {
            JsonObject o = e.getAsJsonObject();
            JsonArray b = o.getAsJsonArray("bounds");
            Rect bounds = a.rect(new Rect(b.get(0).getAsInt(), b.get(1).getAsInt(), b.get(2).getAsInt(), b.get(3).getAsInt()));
            rooms.add(new Room(str(o, "id"), str(o, "building"), o.get("floor").getAsInt(), o.get("y").getAsInt() + a.baseY() - frame.baseY(),
                    bounds, str(o, "function"), str(o, "reach"), strings(o, "portals"), strings(o, "doors"),
                    has(o, "walkable_cells") ? o.get("walkable_cells").getAsInt() : 0));
        }
        List<Door> doors = new ArrayList<>();
        for (JsonElement e : arr(root, "doors")) {
            JsonObject o = e.getAsJsonObject();
            JsonArray cells = o.getAsJsonArray("cells");
            List<BlockPos> sa = new ArrayList<>();
            List<BlockPos> sb = new ArrayList<>();
            for (JsonElement p : o.getAsJsonArray("side_a")) {
                sa.add(a.map(pos(p)));
            }
            for (JsonElement p : o.getAsJsonArray("side_b")) {
                sb.add(a.map(pos(p)));
            }
            BlockPos c0 = a.map(pos(cells.get(0)));
            BlockPos c1 = a.map(pos(cells.get(cells.size() > 1 ? 1 : 0)));
            doors.add(new Door(str(o, "id"), str(o, "kind"), str(o, "passage"),
                    new BlockPos(Math.min(c0.getX(), c1.getX()), Math.min(c0.getY(), c1.getY()), Math.min(c0.getZ(), c1.getZ())),
                    new BlockPos(Math.max(c0.getX(), c1.getX()), Math.max(c0.getY(), c1.getY()), Math.max(c0.getZ(), c1.getZ())),
                    sa, sb, str(o, "room_a"), str(o, "room_b"), has(o, "width") ? o.get("width").getAsInt() : 1, str(o, "reach")));
        }
        List<Stair> stairs = new ArrayList<>();
        for (JsonElement e : arr(root, "stairs")) {
            JsonObject o = e.getAsJsonObject();
            stairs.add(new Stair(str(o, "id"), o.get("width").getAsInt(), str(o, "building"),
                    o.get("y_bottom").getAsInt() + a.baseY() - frame.baseY(), o.get("y_top").getAsInt() + a.baseY() - frame.baseY()));
        }
        List<Bed> beds = new ArrayList<>();
        for (JsonElement e : arr(root, "beds")) {
            JsonObject o = e.getAsJsonObject();
            beds.add(new Bed(str(o, "id"), a.map(pos(o.get("pos_head"))), a.map(pos(o.get("approach"))),
                    a.yaw(has(o, "yaw") ? o.get("yaw").getAsFloat() : 0.0F), str(o, "room"), str(o, "building"), str(o, "role"),
                    str(o, "owner_key"), has(o, "slot") ? o.get("slot").getAsInt() : 0, str(o, "reach")));
        }
        List<Spot> spots = new ArrayList<>();
        for (JsonElement e : arr(root, "spots")) {
            JsonObject o = e.getAsJsonObject();
            spots.add(new Spot(str(o, "id"), str(o, "kind"), str(o, "posture"), a.map(pos(o.get("pos"))),
                    has(o, "approach") ? a.map(pos(o.get("approach"))) : null, has(o, "target") ? a.map(pos(o.get("target"))) : null,
                    a.yaw(has(o, "yaw") ? o.get("yaw").getAsFloat() : 0.0F), str(o, "room"), str(o, "building"), str(o, "zone"),
                    str(o, "door_group"), strings(o, "roles"), str(o, "reach"), has(o, "row") ? o.get("row").getAsInt() : -1,
                    has(o, "col") ? o.get("col").getAsInt() : -1));
        }
        List<Waypoint> wps = new ArrayList<>();
        for (JsonElement e : arr(root, "waypoints")) {
            JsonObject o = e.getAsJsonObject();
            wps.add(new Waypoint(str(o, "id"), a.map(pos(o.get("pos"))), str(o, "kind"), str(o, "ref"), str(o, "room")));
        }
        List<Edge> edges = new ArrayList<>();
        for (JsonElement e : arr(root, "edges")) {
            JsonObject o = e.getAsJsonObject();
            List<BlockPos> via = new ArrayList<>();
            for (JsonElement p : o.getAsJsonArray("via")) {
                via.add(a.map(pos(p)));
            }
            Edge edge = new Edge(edges.size(), str(o, "a"), str(o, "b"), o.get("length").getAsInt(), via, strings(o, "crosses"),
                    has(o, "stairs") && o.get("stairs").getAsBoolean(), has(o, "one_way") && o.get("one_way").getAsBoolean());
            // The extractor wrote some edges twice. A copy is harmless to the router, but the stuck recovery bans an edge by its
            // index: the ban of one copy left the other, and the walker took the same dead edge again (23.10: the steward stood 480
            // ticks at the foot of a cliff in 5 of 5 worlds).
            if (edges.stream().noneMatch(e2 -> e2.sameWay(edge))) {
                edges.add(edge);
            }
        }
        List<Zone> zones = new ArrayList<>();
        for (JsonElement e : arr(root, "zones")) {
            JsonObject o = e.getAsJsonObject();
            JsonArray r = o.getAsJsonArray("rect");
            zones.add(new Zone(str(o, "id"), a.rect(new Rect(r.get(0).getAsInt(), r.get(1).getAsInt(), r.get(2).getAsInt(), r.get(3).getAsInt())),
                    o.get("y").getAsInt() + a.baseY() - frame.baseY()));
        }
        SectLayoutFile file = new SectLayoutFile(new Frame(a.centerX(), a.centerZ(), a.baseY(), a.rotation()), roles, buildings,
                rooms, doors, stairs, beds, spots, wps, edges, zones);
        // Shots are stored as block cells of the file frame (eye cell, aim cell); the cell centre is the point.
        if (has(root, "tour")) {
            for (var e : root.getAsJsonObject("tour").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                file.tour.put(e.getKey(), new Tour(e.getKey(), Vec3.atCenterOf(a.map(pos(o.get("camera")))),
                        Vec3.atCenterOf(a.map(pos(o.get("aim")))), has(o, "fov") ? o.get("fov").getAsFloat() : 55.0F));
            }
        }
        for (JsonElement e : arr(root, "boards")) {
            file.boards.add(a.map(pos(e)));
        }
        if (has(root, "landmarks")) {
            for (var e : root.getAsJsonObject("landmarks").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                file.landmarks.put(e.getKey(), new Landmark(e.getKey(), a.map(pos(o.get("cell"))),
                        has(o, "gate") ? a.map(pos(o.get("gate"))) : null, has(o, "mouth") ? a.map(pos(o.get("mouth"))) : null));
            }
        }
        return file;
    }

    private static boolean has(JsonObject o, String key) {
        JsonElement e = o.get(key);
        return e != null && !e.isJsonNull();
    }

    private static JsonArray arr(JsonObject o, String key) {
        return has(o, key) ? o.getAsJsonArray(key) : new JsonArray();
    }

    private static String str(JsonObject o, String key) {
        JsonElement e = o.get(key);
        return e == null || e.isJsonNull() ? null : e.getAsString();
    }

    private static List<String> strings(JsonObject o, String key) {
        List<String> out = new ArrayList<>();
        if (has(o, key) && o.get(key).isJsonArray()) {
            for (JsonElement e : o.getAsJsonArray(key)) {
                out.add(e.getAsString());
            }
        }
        return List.copyOf(out);
    }

    private static BlockPos pos(JsonElement e) {
        JsonArray a = e.getAsJsonArray();
        return new BlockPos(a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt());
    }
