    /**
     * The bed of a roster member: the bed that names him ({@code owner_key}), else the n-th bed without an owner of
     * his layout role, n = his place among the roster members of that role (roster order, so it never changes with
     * the extraction). Null: the member needs no bed or the world has fewer beds than people.
     */
    public Bed bedFor(String rosterKey, List<String> rosterOrder) {
        for (Bed b : beds.values()) {
            if (rosterKey.equals(b.ownerKey())) {
                return b;
            }
        }
        String role = layoutRole(rosterKey);
        if (role == null) {
            return null;
        }
        int n = 0;
        for (String k : rosterOrder) {
            if (k.equals(rosterKey)) {
                break;
            }
            if (role.equals(layoutRole(k)) && bedNamed(k) == null) {
                n++;
            }
        }
        List<Bed> free = new ArrayList<>();
        for (Bed b : beds.values()) {
            if (role.equals(b.role()) && b.ownerKey() == null) {
                free.add(b);
            }
        }
        free.sort(Comparator.comparingInt(Bed::slot));
        return n < free.size() ? free.get(n) : null;
    }

    private Bed bedNamed(String key) {
        for (Bed b : beds.values()) {
            if (key.equals(b.ownerKey())) {
                return b;
            }
        }
        return null;
    }

