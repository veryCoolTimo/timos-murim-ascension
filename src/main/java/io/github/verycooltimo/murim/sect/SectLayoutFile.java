    public SectLayoutFile(Frame frame, Map<String, String> rosterRole, List<Building> buildings, List<Room> rooms,
                          List<Door> doors, List<Stair> stairs, List<Bed> beds, List<Spot> spots, List<Waypoint> waypoints,
                          List<Edge> edges, List<Zone> zones) {
        this.frame = frame;
        this.rosterRole = Map.copyOf(rosterRole);
        buildings.forEach(b -> this.buildings.put(b.id(), b));
        rooms.forEach(r -> this.rooms.put(r.id(), r));
        doors.forEach(d -> this.doors.put(d.id(), d));
        stairs.forEach(s -> this.stairs.put(s.id(), s));
        beds.forEach(b -> {
            this.beds.put(b.id(), b);
            bedsByHead.put(b.head().asLong(), b);
        });
        spots.forEach(s -> {
            this.spots.put(s.id(), s);
            if (s.room() != null) {
                spotsByRoom.computeIfAbsent(s.room(), k -> new ArrayList<>()).add(s);
            }
        });
        waypoints.forEach(w -> this.waypoints.put(w.id(), w));
        this.edges.addAll(edges);
        zones.forEach(z -> this.zones.put(z.id(), z));
        for (Edge e : edges) {
            adjacency.computeIfAbsent(e.a(), k -> new ArrayList<>()).add(e);
            if (!e.oneWay()) {
                adjacency.computeIfAbsent(e.b(), k -> new ArrayList<>()).add(e);
            }
        }
    }

